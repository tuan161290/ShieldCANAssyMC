# Generates Core\Lang\StringsEn.inc from the WPF app's Core.Lang\StringsEn.resx (same keys as the C# Loc.T).
# Run ONCE while porting; afterwards StringsEn.inc is the master copy for the C++ app (edit wording there).
# Running it again OVERWRITES the .inc. Keep this file ASCII-only: Windows PowerShell 5.1 reads a BOM-less
# script as ANSI.
#
#   powershell -ExecutionPolicy Bypass -File tools\gen-strings.ps1 [-Resx <path to resx>]
param(
    [string]$Resx = (Join-Path $PSScriptRoot '..\..\ShieldCanAssy.Core\Core.Lang\StringsEn.resx')
)

$ErrorActionPreference = 'Stop'
$outDir = (Resolve-Path (Join-Path $PSScriptRoot '..\Core\Lang')).Path
$out = Join-Path $outDir 'StringsEn.inc'

[xml]$x = Get-Content -LiteralPath $Resx -Encoding UTF8
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// English UI text: { key, text }. Generated by tools\gen-strings.ps1 from the WPF StringsEn.resx, then edited by hand.')
[void]$sb.AppendLine('// UTF-8 (compiled with /utf-8). Placeholders follow .NET string.Format: {n[,w][:fmt]} - see Loc::Format.')
foreach ($d in ($x.root.data | Sort-Object { $_.name })) {
    $v = [string]$d.value
    $v = $v.Replace('\', '\\').Replace('"', '\"').Replace("`r`n", '\n').Replace("`n", '\n').Replace("`r", '').Replace("`t", '\t')
    $k = [string]$d.name
    [void]$sb.AppendLine(('{{ "{0}", "{1}" }},' -f $k, $v))
}
[IO.File]::WriteAllText($out, $sb.ToString(), (New-Object Text.UTF8Encoding($false)))
Write-Host ("Wrote {0} strings -> {1}" -f $x.root.data.Count, $out)
